const q = (title, concept, prompt, choices, answer, explanation) => ({
  title,
  concept,
  prompt,
  choices,
  answer,
  explanation,
  type: "quiz",
  hint: explanation,
  solution: choices[answer],
});
const code = (title, concept, task, starter, solution, checks, hint) => ({
  title,
  concept,
  task,
  starter,
  solution,
  checks,
  hint,
  type: "code",
});
const sh = (title, concept, task, goal, solution, hint) => ({
  title,
  concept,
  task,
  goal,
  solution,
  hint,
  type: "terminal",
});
